#!/usr/bin/env node
/* Build the Capacitor `www/` folder from the existing browser frontend.
 *
 * This is intentionally a copy, not a rewrite: the browser version at
 * http://127.0.0.1:8000 remains byte-for-byte equivalent. A tiny generated
 * `js/native-config.js` lets the Android build point API calls at a deployed
 * HTTPS backend without editing any application source.
 */
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SOURCE = join(ROOT, "frontend");
const TARGET = join(ROOT, "www");

const configured = (process.env.JARVIS_BACKEND_URL || "").trim().replace(/\/+$/, "");
if (configured && !/^https:\/\//i.test(configured) && !/^http:\/\/localhost(:\d+)?$/i.test(configured)) {
  console.error("[jarvis] JARVIS_BACKEND_URL must be an https:// URL (http://localhost is dev-only).");
  process.exit(2);
}

rmSync(TARGET, { recursive: true, force: true });
mkdirSync(TARGET, { recursive: true });
cpSync(SOURCE, TARGET, { recursive: true });

const safeBase = configured.replace(/[\u2028\u2029<>"'\\]/g, "");
writeFileSync(
  join(TARGET, "js", "native-config.js"),
  `/* Generated by scripts/build-www.mjs — do not edit. */\n` +
    `window.JARVIS_API_BASE = ${JSON.stringify(safeBase)};\n` +
    `window.JARVIS_NATIVE_BUILD = true;\n`,
  "utf8",
);

console.log(`[jarvis] www/ built from frontend/ (backend base: ${configured || "same origin"})`);
