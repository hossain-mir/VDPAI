#!/usr/bin/env node
/* Build the Capacitor `www/` folder from frontend/.
 *
 * The packaged HUD always loads its own local assets, so it starts offline and
 * never depends on a backend.  An optional default backend URL can be baked in
 * for convenience (HSAI_BACKEND_URL or the legacy JARVIS_BACKEND_URL), but it
 * is only a default for the editable Backend Server setting.  No secrets are
 * ever embedded in the web bundle.
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SOURCE = join(ROOT, "frontend");
const TARGET = join(ROOT, "www");

const configured = String(process.env.HSAI_BACKEND_URL || process.env.JARVIS_BACKEND_URL || "")
  .trim()
  .replace(/\/+$/, "");

if (configured && !/^https:\/\//i.test(configured)) {
  console.error("[hsai] HSAI_BACKEND_URL must be an https:// URL. Use the in-app setting for development.");
  process.exit(2);
}

rmSync(TARGET, { recursive: true, force: true });
mkdirSync(TARGET, { recursive: true });
cpSync(SOURCE, TARGET, { recursive: true });

const safeBase = configured.replace(/[\u2028\u2029<>"'\\]/g, "");
writeFileSync(
  join(TARGET, "js", "native-config.js"),
  `/* Generated by scripts/build-www.mjs — do not edit. */\n` +
    `window.HSAI_DEFAULT_BACKEND_URL = ${JSON.stringify(safeBase)};\n` +
    `window.HSAI_NATIVE_BUILD = true;\n` +
    `window.HSAI_BUILD = "android";\n`,
  "utf8",
);

const indexPath = join(TARGET, "index.html");
const html = readFileSync(indexPath, "utf8");
const marker = '<script src="/js/native-config.js"></script>';
const entry = '<script type="module" src="/js/app.js"></script>';
if (!html.includes(marker)) {
  console.error("[hsai] frontend/index.html must load /js/native-config.js before app.js.");
  process.exit(2);
}
if (!html.includes(entry)) {
  console.error("[hsai] frontend/index.html is missing the app.js module entry point.");
  process.exit(2);
}
if (!html.includes("VDPAI")) {
  console.error("[vdpai] frontend/index.html is missing VDPAI branding.");
  process.exit(2);
}

console.log(`[vdpai] www/ built from frontend/ (default backend: ${configured || "none"})`);
